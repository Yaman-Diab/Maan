import 'package:intl/intl.dart';

/// تنسيق المبالغ للعرض — فواصل آلاف، وبلا كسور لو المبلغ صحيح.
///
/// ⚠️ **أرقام لاتينية دائماً حتى بالواجهة العربية** (`'en'` مثبّتة لا
/// `context.locale`) — قرار اتساق مع باقي التطبيق: التواريخ
/// (`createdAt.toString().split(' ').first`) والنِّسب (`'$percentage%'`)
/// وأعداد الأصوات كلها لاتينية أصلاً. لو مرّرنا اللغة الحالية، رح
/// تطلع مبالغ بأرقام هندية (٦٥٠٬٠٠٠) جنب عدّادات لاتينية بنفس
/// البطاقة — تنافر بصري أسوأ من «عدم التوطين».
///
/// تغيير هالقرار مستقبلاً بده يشمل **كل** الأرقام بالتطبيق مرة وحدة،
/// لا هالدالة لحالها.
class AmountFormatter {
  AmountFormatter._();

  static final NumberFormat _grouped = NumberFormat.decimalPattern('en');

  /// `650000` → `"650,000"` · `1234.5` → `"1,234.5"`.
  static String format(num value) => _grouped.format(value);
}
